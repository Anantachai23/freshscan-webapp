/**
 * เกณฑ์ตัดเกรดจากคะแนนรวม 20 คะแนน (ผลรวมของ 2 criteria x 10 คะแนน ต่อประเภทอาหารทะเล)
 * A: 16-20 (สดมาก) · B: 11-15 (ยังใช้ได้) · C: 0-10 (เริ่มเสื่อมคุณภาพ)
 */
export const SCORE20_GRADE_THRESHOLDS: { grade: FreshnessGrade; min: number; max: number }[] = [
  { grade: 'A', min: 16, max: 20 },
  { grade: 'B', min: 11, max: 15 },
  { grade: 'C', min: 0, max: 10 },
];

export function gradeFromScore20(total: number): FreshnessGrade {
  const found = SCORE20_GRADE_THRESHOLDS.find((t) => total >= t.min && total <= t.max);
  return found?.grade ?? 'C';
}
